export const DOT_ROWS = 7;

export function dotGlyph(ch: string): string[] {
  return G[ch] ?? G[ch.toUpperCase()] ?? G["?"];
}

/** Lay text out in dots: returns the lit cells and the size in dots. `wrap` is the most
    dots a line may hold (lines break at spaces); `\n` forces a break. */
export function layoutDots(text: string, { wrap = Infinity, tracking = 1, leading = 2, align = "left" }: { wrap?: number; tracking?: number; leading?: number; align?: "left" | "center" | "right" } = {}) {
  const width = (w: string) => [...w].reduce((n, ch, i) => n + dotGlyph(ch)[0].length + (i ? tracking : 0), 0);
  const space = dotGlyph(" ")[0].length + 2 * tracking;
  const lines: string[] = [];
  for (const para of text.split("\n")) {
    let line = "";
    for (const word of para.split(/\s+/).filter(Boolean)) {
      const next = line ? `${line} ${word}` : word;
      if (line && width(line) + space + width(word) > wrap) {
        lines.push(line);
        line = word;
      } else line = next;
    }
    lines.push(line);
  }
  const lineW = (l: string) => l.split(" ").reduce((n, w, i) => n + width(w) + (i ? space : 0), 0);
  const cols = Math.max(1, ...lines.map(lineW));
  const rows = lines.length * DOT_ROWS + (lines.length - 1) * leading;
  const lit: [number, number][] = [];
  lines.forEach((l, li) => {
    let x = align === "center" ? Math.floor((cols - lineW(l)) / 2) : align === "right" ? cols - lineW(l) : 0;
    const y0 = li * (DOT_ROWS + leading);
    l.split(" ").forEach((w, wi) => {
      if (wi) x += space;
      [...w].forEach((ch, ci) => {
        if (ci) x += tracking;
        const g = dotGlyph(ch);
        g.forEach((row, ry) => [...row].forEach((c, rx) => c === "#" && lit.push([x + rx, y0 + ry])));
        x += g[0].length;
      });
    });
  });
  return { lit, cols, rows };
}
